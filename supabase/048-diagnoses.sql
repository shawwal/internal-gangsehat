-- Shared diagnosis reference list for Diagnosa Primer/Sekunder comboboxes.
-- Any authenticated internal user can read and add new diagnoses; this is a
-- shared clinical vocabulary, not branch-scoped data.

create table if not exists public.diagnoses (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  is_active boolean not null default true,
  created_by uuid references public.internal_profiles(id),
  created_at timestamptz not null default now()
);

create unique index if not exists diagnoses_name_unique_idx on public.diagnoses (upper(name));

alter table public.diagnoses enable row level security;

create policy "diagnoses_select_all" on public.diagnoses
  for select to authenticated using (true);

create policy "diagnoses_insert_all" on public.diagnoses
  for insert to authenticated with check (true);

